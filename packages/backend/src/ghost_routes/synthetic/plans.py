"""Original plan-like synthetic PDFs with exact ground truth.

Pages are drawn directly in PDF syntax (no third-party content), are visibly
marked SYNTHETIC, and depict the fictional Ashgrove campus. Ground truth is
recorded in page points (displayed frame, origin top-left) so model outputs
can be scored without reference to any model.
"""

from __future__ import annotations

import math
import zlib
from dataclasses import dataclass, field
from typing import Any

PAGE_W, PAGE_H = 1224.0, 792.0  # 17 x 11 in landscape
# Site metres -> page points: 1 m = 6 pt; site origin at page (180, 560), site y up.
M_TO_PT = 6.0
ORIGIN = (180.0, 560.0)


def site_to_page(p: tuple[float, float]) -> tuple[float, float]:
    return (ORIGIN[0] + p[0] * M_TO_PT, ORIGIN[1] - p[1] * M_TO_PT)


@dataclass
class Label:
    cls: str
    text: str
    bbox: tuple[float, float, float, float]  # page points, top-left origin
    phase_refs: tuple[str, ...] = ()
    geometry: tuple[tuple[float, float], ...] = ()
    properties: dict[str, Any] = field(default_factory=dict)


@dataclass
class PlanSpec:
    sheet_id: str
    title: str
    revision: str
    fences: list[tuple[str, list[tuple[float, float]]]]  # (phase label, site polyline)
    notes: list[str]
    dimension_text: str | None = "MIN 6' PEDESTRIAN PATH"
    rotation: int = 0


class _Page:
    def __init__(self) -> None:
        self.ops: list[str] = []
        self.labels: list[Label] = []

    def line(self, pts: list[tuple[float, float]], width: float = 1.0, dash: tuple[float, float] | None = None, gray: float = 0.0) -> None:
        # PDF user space has y up; convert from the top-left frame.
        self.ops.append(f"{gray:.2f} G {width:.2f} w " + (f"[{dash[0]:.1f} {dash[1]:.1f}] 0 d " if dash else "[] 0 d "))
        x0, y0 = pts[0]
        self.ops.append(f"{x0:.2f} {PAGE_H - y0:.2f} m " + " ".join(f"{x:.2f} {PAGE_H - y:.2f} l" for x, y in pts[1:]) + " S")

    def text(self, x: float, y_top: float, s: str, size: float = 9.0) -> tuple[float, float, float, float]:
        esc = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        baseline = y_top + size * 0.8
        self.ops.append(f"BT /F1 {size:.1f} Tf {x:.2f} {PAGE_H - baseline:.2f} Td ({esc}) Tj ET")
        width = 0.6 * size * len(s)  # Helvetica average; bbox is approximate, used only with tolerance
        return (x, y_top, x + width, y_top + size)


def _pdf(ops: list[str], rotation: int) -> bytes:
    content = zlib.compress("\n".join(ops).encode("latin-1"))
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        (f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PAGE_W:.0f} {PAGE_H:.0f}] /Rotate {rotation} "
         "/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>").encode(),
        b"<< /Length " + str(len(content)).encode() + b" /Filter /FlateDecode >>\nstream\n" + content + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    ]
    out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, body in enumerate(objs, start=1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R /Info << /Producer (ghost-routes synthetic) >> >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def render_plan(spec: PlanSpec, network_edges: list[tuple[str, list[tuple[float, float]], str]]) -> tuple[bytes, list[Label]]:
    """Draw paths, fences, labels, notes and a title block. Returns PDF bytes and ground truth labels."""
    if spec.rotation:
        raise NotImplementedError("rotated synthetic pages are generated by rotating the network geometry instead")
    pg = _Page()
    # Border and title block.
    pg.line([(18, 18), (PAGE_W - 18, 18), (PAGE_W - 18, PAGE_H - 18), (18, PAGE_H - 18), (18, 18)], width=1.2)
    # "context" labels mark real sheet text that no scored class covers (title block, headers, scale).
    def context(x: float, y: float, t: str, size: float) -> None:
        pg.labels.append(Label("context", t, pg.text(x, y, t, size)))

    context(30, PAGE_H - 50, f"SYNTHETIC FIXTURE - FICTIONAL ASHGROVE CAMPUS - {spec.title}", 10)
    context(PAGE_W - 260, PAGE_H - 50, f"SHEET NUMBER {spec.sheet_id}", 10)
    context(PAGE_W - 260, PAGE_H - 36, f"REVISION {spec.revision}", 9)
    # Paths (drawn as double lines would be realistic; a single 2 pt line keeps symbols simple).
    for eid, pts, label in network_edges:
        pp = [site_to_page(p) for p in pts]
        pg.line(pp, width=2.0, gray=0.35)
        pg.labels.append(Label("path", label or eid, _bounds(pp), geometry=tuple(pp), properties={"edge_id": eid}))
    # Fences with phase labels near their midpoint.
    for phase, pts in spec.fences:
        pp = [site_to_page(p) for p in pts]
        pg.line(pp, width=1.4, dash=(6, 3))
        pg.labels.append(Label("barrier", f"{phase} FENCING", _bounds(pp), phase_refs=(phase,), geometry=tuple(pp)))
        mx, my = pp[len(pp) // 2]
        bb = pg.text(mx + 8, my - 22, f"{phase} FENCING", 8)
        pg.labels.append(Label("legend_entry", f"{phase} FENCING", bb, phase_refs=(phase,)))
    # Legend.
    context(PAGE_W - 300, 60, "LEGEND", 10)
    pg.line([(PAGE_W - 300, 84), (PAGE_W - 250, 84)], width=1.4, dash=(6, 3))
    pg.labels.append(Label("legend_entry", "TEMPORARY FENCING", pg.text(PAGE_W - 240, 79, "TEMPORARY FENCING", 8)))
    pg.line([(PAGE_W - 300, 102), (PAGE_W - 250, 102)], width=2.0, gray=0.35)
    pg.labels.append(Label("legend_entry", "PEDESTRIAN PATH", pg.text(PAGE_W - 240, 97, "PEDESTRIAN PATH", 8)))
    # Notes.
    y = 140.0
    context(PAGE_W - 300, y, "PHASING NOTES", 10)
    for i, note in enumerate(spec.notes, start=1):
        y += 16
        bb = pg.text(PAGE_W - 300, y, f"{i}. {note}", 7)
        refs = tuple(sorted({f"PHASE {m}" for m in _phase_nums(note)}))
        pg.labels.append(Label("note", f"{i}. {note}", bb, phase_refs=refs))
    if spec.dimension_text:
        bb = pg.text(ORIGIN[0] + 20, ORIGIN[1] + 30, spec.dimension_text, 8)
        pg.labels.append(Label("dimension", spec.dimension_text, bb, properties={"value_m": round(6 * 0.3048, 6)}))
    # Building labels.
    for name, site in (("HALDEN LAB", (-8, -10)), ("MERROW LIBRARY", (100, 62))):
        x, yy = site_to_page(site)
        bb = pg.text(x, yy, name, 9)
        pg.labels.append(Label("place_label", name, bb))
    # Graphic scale bar: 0..20 m = 120 pt.
    sx, sy = 60.0, PAGE_H - 90
    pg.line([(sx, sy), (sx + 120, sy)], width=3)
    context(sx - 2, sy - 16, "0", 7)
    context(sx + 114, sy - 16, "20 M", 7)
    context(sx, sy + 6, "SCALE IN METRES (1 M = 6 PT ON THIS SHEET)", 6)
    return _pdf(pg.ops, 0), pg.labels


def _bounds(pts: list[tuple[float, float]]) -> tuple[float, float, float, float]:
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return (min(xs), min(ys), max(xs), max(ys))


def _phase_nums(text: str) -> list[str]:
    import re

    return re.findall(r"PHASE\s+(\d+)", text.upper())


def ashgrove_edges() -> list[tuple[str, list[tuple[float, float]], str]]:
    from ghost_routes.synthetic.cases import base_edges

    return [(e.id, list(e.geometry), "") for e in base_edges()]


def project_q_plan(revision: str) -> tuple[bytes, list[Label], PlanSpec]:
    """Project Q's sheet. Revision B moves the fence to also close the B-C walk (e2)."""
    fences: list[tuple[str, list[tuple[float, float]]]] = [("PHASE 1", [(55, 20), (65, 20), (65, 30)]), ("PHASE 1", [(85, 45), (95, 55)])]
    notes = ["PHASE 1 CLOSES THE B-E CROSSING AND THE E-F WALK.",
             "KEEP THE NORTH WALK OPEN AT ALL TIMES."]
    if revision == "B":
        fences.append(("PHASE 1", [(90, -5), (90, 5)]))
        notes = ["PHASE 1 CLOSES THE B-E CROSSING, THE E-F WALK AND THE B-C WALK.",
                 "PEDESTRIANS DETOUR VIA THE WEST WALK DURING PHASE 1."]
    spec = PlanSpec(sheet_id="ASH-Q1", title="PROJECT Q UTILITY TRENCH (FICTIONAL)", revision=revision,
                    fences=fences, notes=notes)
    data, labels = render_plan(spec, ashgrove_edges())
    return data, labels, spec


def project_p_plan() -> tuple[bytes, list[Label], PlanSpec]:
    spec = PlanSpec(sheet_id="ASH-P1", title="PROJECT P STAIR REPAIR (FICTIONAL)", revision="A",
                    fences=[("PHASE 1", [(115, 15), (125, 15), (125, 35), (115, 35)])],
                    notes=["PHASE 1 CLOSES THE C-F STAIRS.", "STEP-FREE ROUTE VIA THE E-F WALK."])
    data, labels = render_plan(spec, ashgrove_edges())
    return data, labels, spec


def benchmark_plans() -> list[tuple[str, str, bytes, list[Label]]]:
    """(plan family, revision, pdf, labels). Families split train/eval by project, not by crop."""
    out = []
    d, lab, _ = project_p_plan()
    out.append(("ashgrove-P", "A", d, lab))
    for rev in ("A", "B"):
        d, lab, _ = project_q_plan(rev)
        out.append(("ashgrove-Q", rev, d, lab))
    # A differently laid out family: rotated and scaled network geometry, different notes.
    rot = math.radians(28)

    def tf(p: tuple[float, float]) -> tuple[float, float]:
        return (0.8 * (p[0] * math.cos(rot) - p[1] * math.sin(rot)) + 20, 0.8 * (p[0] * math.sin(rot) + p[1] * math.cos(rot)) - 30)

    edges = [(eid, [tf(p) for p in pts], lbl) for eid, pts, lbl in ashgrove_edges()]
    spec = PlanSpec(sheet_id="LYN-R1", title="LYNDALE QUAD RESURFACING (FICTIONAL, ROTATED LAYOUT)", revision="A",
                    fences=[("PHASE 1", [tf((10, -6)), tf((10, 6))]), ("PHASE 2", [tf((70, 44)), tf((70, 56))])],
                    notes=["PHASE 1 CLOSES THE WEST WALK.", "PHASE 2 CLOSES THE SOUTH LINK.",
                           "MAINTAIN ACCESS TO THE LIBRARY ENTRANCE IN BOTH PHASES."],
                    dimension_text="MIN 5' CLEAR WIDTH")
    d, lab = render_plan(spec, edges)
    for lb in lab:
        if lb.cls == "dimension":
            lb.properties["value_m"] = round(5 * 0.3048, 6)
    out.append(("lyndale", "A", d, lab))
    return out
