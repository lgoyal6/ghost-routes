"""Intentional demo data: the fictional flagship with synthetic source sheets.

Everything here is labeled synthetic and reviewed by a scripted fixture
reviewer, never presented as a human or professional review.
"""

from __future__ import annotations

from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from ghost_routes.persistence import repo
from ghost_routes.persistence import schema as S
from ghost_routes.persistence.db import transaction
from ghost_routes.services.documents import ingest_pdf
from ghost_routes.synthetic.flagship import flagship_input
from ghost_routes.synthetic.plans import project_p_plan, project_q_plan

SCRIPTED = "scripted-fixture-review"


def seed_flagship(s: Session, namespace: str = "ashgrove") -> dict[str, Any]:
    inp = flagship_input()
    lineage_id = f"{namespace}-net"
    if s.get(S.NetworkLineage, lineage_id) is not None:
        sc = s.get(S.ScenarioRow, f"{namespace}-works")
        return {"already_seeded": True, "scenario_id": f"{namespace}-works",
                "scenario_revision_id": sc.head_revision_id if sc else None}
    repo.create_lineage(s, lineage_id, "Ashgrove campus pedestrian network (fictional)", inp.network.frame, synthetic=True)
    net_rev = repo.commit_network_revision(s, lineage_id, inp.network.nodes, inp.network.edges, inp.network.coverage,
                                           author=SCRIPTED, author_kind="scripted", note="seeded synthetic baseline",
                                           expected_head=0)
    plans = {"P": project_p_plan(), "Q": project_q_plan("A")}
    proj_revs: dict[str, str] = {}
    sources: dict[str, Any] = {}
    for key, (pdf, _labels, spec) in plans.items():
        pid = f"{namespace}-{key}"
        src = ingest_pdf(s, pdf, filename=f"{spec.sheet_id}-rev{spec.revision}.pdf", project_id=pid,
                         project_title=spec.title.title(), revision_label=spec.revision, reuse_status="synthetic_original",
                         synthetic=True, note="original synthetic sheet generated by ghost_routes.synthetic.plans")
        sources[key] = src
        snap = inp.project(key)
        snap = snap.model_copy(update={"project_id": pid,
                                       "coverage": tuple(c.model_copy(update={"scope": pid}) for c in snap.coverage)})
        proj_revs[pid] = repo.commit_project_revision(s, snap, frame_id=inp.network.frame.id,
                                                      plan_revision_id=src["plan_revision_id"], expected_head=None,
                                                      note=f"reviewed model of sheet {spec.sheet_id} rev {spec.revision}")
    for prof in inp.profiles:
        try:
            repo.latest_profile(s, prof.id)
        except repo.NotFound:
            repo.save_profile(s, prof)
    refs = []
    for r in inp.requirements:
        stored = repo.save_requirement(s, r.model_copy(update={"id": f"{namespace}-{r.id}"}))
        refs.append((stored.id, stored.version))
    sid = f"{namespace}-works"
    repo.create_scenario(s, sid, "Ashgrove spring works (fictional)", lineage_id)
    scn = inp.scenario.model_copy(update={"id": sid, "project_ids": tuple(sorted(proj_revs))})
    srid = repo.commit_scenario_revision(s, scn, network_revision_id=net_rev, project_revision_ids=proj_revs,
                                         requirement_refs=refs, expected_head=None)
    return {"already_seeded": False, "scenario_id": sid, "scenario_revision_id": srid, "network_lineage_id": lineage_id,
            "network_revision_id": net_rev, "project_revisions": proj_revs,
            "sources": {k: {"plan_revision_id": v["plan_revision_id"], "sheet_id": v["sheets"][0]["sheet_id"]}
                        for k, v in sources.items()}}


def seed_demo(namespace: str = "ashgrove") -> dict[str, Any]:
    with transaction() as s:
        return seed_flagship(s, namespace)


def import_revised_q(s: Session, namespace: str = "ashgrove") -> dict[str, Any]:
    """Import Project Q's revision B sheet (adds a closure of the B-C walk)."""
    pdf, _labels, spec = project_q_plan("B")
    return ingest_pdf(s, pdf, filename=f"{spec.sheet_id}-revB.pdf", project_id=f"{namespace}-Q",
                      project_title=spec.title.title(), revision_label="B", reuse_status="synthetic_original",
                      synthetic=True, note="revised synthetic sheet: adds a phase 1 fence across the B-C walk")


def demo_status(s: Session) -> dict[str, Any]:
    scenarios = s.scalars(select(S.ScenarioRow).order_by(S.ScenarioRow.created_at)).all()
    return {"scenarios": [{"id": x.id, "title": x.title, "head_revision_id": x.head_revision_id} for x in scenarios]}
