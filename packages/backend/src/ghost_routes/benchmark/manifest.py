"""The fixed benchmark manifest: inputs, independent labels, splits and declared thresholds.

Labels come from the synthetic generator's ground truth, never from model output.
``write_manifest`` regenerates the tracked files; ``check_inputs`` proves the PDFs
being evaluated are byte-identical to the ones the manifest declared.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict
from pathlib import Path
from typing import Any

from ghost_routes.benchmark.evaluate import Tolerances
from ghost_routes.synthetic.plans import Label, benchmark_plans

SCHEMA = "ghost-routes/benchmark/1"
# Splits are by plan family, not by crop: no held-out sheet shares a layout with the dev family.
DEV_FAMILIES = {"ashgrove-P"}
# Declared before any held-out evaluation; changing them must be recorded in the manifest history.
THRESHOLDS = {
    "manual_graph": {"status_correctness": 1.0, "false_supported": 0},
    "full_pipeline_held_out": {"false_connections": 0, "phase_text_recall_min": 0.6, "note_recall_min": 0.5,
                               "path_recall_min": 0.8, "path_precision_min": 0.8,
                               "barrier_recall_min": 0.8, "barrier_precision_min": 0.8,
                               "geometry_median_error_m_max": 1.0, "phase_assignment_min": 0.9},
}
# Every change to inputs, labels or thresholds is recorded here, with whether any model result had been seen.
HISTORY = [
    {"date": "2026-10-31", "change": "initial manifest", "model_results_seen": False},
    {"date": "2026-10-31", "change": "labeled the two generic legend lines; marked title block, headers and scale text as "
     "unscored context. PDFs unchanged.", "model_results_seen": False},
    {"date": "2026-10-31", "change": "note only, thresholds unchanged: the first live run met every declared threshold, but "
     "the thresholds covered recall and false connections, not precision or geometry, where the model did poorly (path and "
     "barrier recall 0). Precision and geometry thresholds belong in the next declaration, set before the next held-out run.",
     "model_results_seen": True},
    {"date": "2026-11-01", "change": "added path and barrier precision and recall (0.8 each), median geometry error (1 m) "
     "and phase assignment (0.9) thresholds for the held-out full pipeline, declared before vector geometry extraction was "
     "written or run on any sheet. Text precision is still not thresholded: duplicate text proposals are separate work.",
     "model_results_seen": True},
]
REAL_PLANS = [{
    "id": "uiowa-J.01",
    "url": "https://facilities.uiowa.edu/sites/facilities.uiowa.edu/files/2024-05/W.01.pdf",
    "sha256": "998d212b936138af21095459eb2b9182b1e9b4d56f1ff1f691b1f7c26a93371a",
    "scored": False,
    "reason": "no human-checked labels exist yet; real-plan results are reported as counts, not accuracy",
}]


def label_dict(lb: Label) -> dict[str, Any]:
    return {"cls": lb.cls, "label": lb.text, "bbox": [round(v, 3) for v in lb.bbox],
            "geometry": [[round(x, 3), round(y, 3)] for x, y in lb.geometry],
            "phase_refs": list(lb.phase_refs), "properties": dict(lb.properties)}


def sheet_id(family: str, revision: str) -> str:
    return f"{family}-{revision}"


def build() -> tuple[dict[str, Any], dict[str, list[dict[str, Any]]], dict[str, bytes]]:
    sheets, labels, pdfs = [], {}, {}
    for family, rev, pdf, lbs in benchmark_plans():
        sid = sheet_id(family, rev)
        labels[sid] = [label_dict(lb) for lb in lbs]
        pdfs[sid] = pdf
        counts: dict[str, int] = {}
        for lb in lbs:
            counts[lb.cls] = counts.get(lb.cls, 0) + 1
        sheets.append({"id": sid, "family": family, "revision": rev, "split": "dev" if family in DEV_FAMILIES else "held_out",
                       "synthetic": True, "pdf_sha256": hashlib.sha256(pdf).hexdigest(), "labels_file": f"labels/{sid}.json",
                       "label_counts": dict(sorted(counts.items()))})
    manifest = {"schema": SCHEMA, "inputs": "generated by ghost_routes.synthetic.plans (original, fictional, visibly marked SYNTHETIC)",
                "tolerances": asdict(Tolerances()), "thresholds": THRESHOLDS, "history": HISTORY, "sheets": sheets, "real_plans": REAL_PLANS}
    return manifest, labels, pdfs


def write_manifest(root: Path) -> Path:
    manifest, labels, _ = build()
    (root / "labels").mkdir(parents=True, exist_ok=True)
    for sid, lbs in labels.items():
        (root / "labels" / f"{sid}.json").write_text(json.dumps(lbs, indent=1) + "\n")
    path = root / "manifest.json"
    path.write_text(json.dumps(manifest, indent=1) + "\n")
    return path


def load(root: Path) -> tuple[dict[str, Any], dict[str, list[dict[str, Any]]]]:
    manifest = json.loads((root / "manifest.json").read_text())
    labels = {s["id"]: json.loads((root / s["labels_file"]).read_text()) for s in manifest["sheets"]}
    return manifest, labels


def check_inputs(manifest: dict[str, Any]) -> dict[str, bytes]:
    """Regenerate the input PDFs and require their hashes to match the manifest."""
    _, _, pdfs = build()
    for s in manifest["sheets"]:
        got = hashlib.sha256(pdfs[s["id"]]).hexdigest()
        if got != s["pdf_sha256"]:
            raise ValueError(f"input {s['id']} changed: manifest {s['pdf_sha256'][:12]}, generated {got[:12]}; "
                             "regenerate the manifest deliberately and record why")
    return pdfs
